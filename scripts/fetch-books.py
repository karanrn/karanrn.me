#!/usr/bin/env python3
"""Sync data/books.yaml from Goodreads shelf RSS feeds.

Goodreads has no public API any more, but each shelf of a public profile has an
RSS feed (100 books per page). This pulls the `currently-reading` and `read`
shelves and rewrites data/books.yaml; it is generated, so don't edit it by hand.

Usage: fetch-books.py <goodreads user id>
"""

import email.utils
import re
import sys
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "books.yaml"
FEED = "https://www.goodreads.com/review/list_rss/{user}?"
# Goodreads rejects requests without a browser-like User-Agent.
UA = "Mozilla/5.0 (X11; Linux x86_64) karanrn.me-book-sync/1.0"


def shelf(user, name):
    """All items on a shelf, following the feed's pagination."""
    items, page = [], 1
    while True:
        url = FEED.format(user=user) + urllib.parse.urlencode({"shelf": name, "page": page})
        req = urllib.request.Request(url, headers={"User-Agent": UA})
        with urllib.request.urlopen(req, timeout=30) as resp:
            channel = ET.fromstring(resp.read()).find("channel")
        if channel is None:
            sys.exit(f"unexpected response for shelf {name!r}; is the Goodreads profile public?")
        batch = channel.findall("item")
        if not batch:
            return items
        items += batch
        page += 1


def date(text):
    """RFC 822 date from the feed as YYYY-MM-DD, or None."""
    text = (text or "").strip()
    return email.utils.parsedate_to_datetime(text).date().isoformat() if text else None


def book(item):
    title = " ".join(item.findtext("title").split())
    # Goodreads appends the series, e.g. "Inferno (Robert Langdon, #4)".
    series = None
    m = re.search(r"\s*\(([^()]*#[\d.]+)\)$", title)
    if m:
        series, title = m.group(1), title[:m.start()]
    main, _, subtitle = title.partition(": ")
    entry = {
        "title": main.strip(),
        "subtitle": subtitle.strip() or None,
        "series": series,
        "author": item.findtext("author_name").strip(),
        "url": f"https://www.goodreads.com/book/show/{item.findtext('book_id').strip()}",
        "rating": int(item.findtext("user_rating") or 0) or None,  # 0 means unrated
        "read": date(item.findtext("user_read_at")),
        "added": date(item.findtext("user_date_added")),
    }
    # The page groups by this; books with no finish date go under "undated".
    entry["year"] = entry["read"][:4] if entry["read"] else "undated"
    return {k: v for k, v in entry.items() if v is not None}


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__.strip().splitlines()[-1])
    user = sys.argv[1]
    try:
        reading = [book(i) for i in shelf(user, "currently-reading")]
        read = [book(i) for i in shelf(user, "read")]
    except (OSError, ET.ParseError) as e:  # network errors are OSErrors
        sys.exit(f"could not fetch Goodreads shelves: {e}")
    # Newest first; books without a finish date go last, by when they were shelved.
    read.sort(key=lambda b: (b.get("read") is not None, b.get("read") or "", b.get("added") or ""), reverse=True)

    # A broken or truncated feed shouldn't wipe the page: keep the old file if the
    # read shelf suddenly shrinks a lot (removing a few books is fine).
    if OUT.exists():
        old = len((yaml.safe_load(OUT.read_text()) or {}).get("read") or [])
        if len(read) < old * 0.8:
            sys.exit(f"refusing to overwrite {OUT.relative_to(ROOT)}: feed has {len(read)} read books, file has {old}")

    header = (f"# Generated by `make books` from https://www.goodreads.com/user/show/{user}\n"
              "# Don't edit by hand: changes are overwritten on the next sync.\n")
    body = yaml.safe_dump({"profile": f"https://www.goodreads.com/user/show/{user}",
                           "reading": reading, "read": read},
                          sort_keys=False, allow_unicode=True, width=1000)
    OUT.write_text(header + body)
    print(f"{OUT.relative_to(ROOT)}: {len(reading)} currently reading, {len(read)} read")


if __name__ == "__main__":
    main()
